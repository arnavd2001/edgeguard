#!/usr/bin/env python3
"""
Emit LaTeX macros and tables from experiments/results/*.json so that every
number in the thesis is traceable to a run.  Output: report/generated/*.tex

Usage:
    python experiments/make_tables.py
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent
R = json.loads((ROOT / "results" / "results.json").read_text())
A = json.loads((ROOT / "results" / "analysis.json").read_text())
OUT = ROOT.parent / "report" / "generated"
OUT.mkdir(parents=True, exist_ok=True)
SC = R["scenario_eval"]["scenarios"]

LABEL = {
    "CLEAN": "Clean (no attack)", "BFA_RANDOM": "BFA, random bit", "BFA_SIGN_BIT": "BFA, sign bit",
    "BFA_PROGRESSIVE": "BFA, progressive", "SUPPLY_STEG": "Supply chain, LSB stego",
    "SUPPLY_DISTRIBUTED": "Supply chain, distributed", "ADV_TEXT_INJECTION": "Adversarial, text injection",
    "ADV_SAFETY_BYPASS": "Adversarial, safety bypass", "EXFIL_PROBE": "Training-data exfil.\\ probe",
    "SYNERGY": "Synergy (BFA + adversarial)",
}
TYPE_TEX = lambda t: t.replace("_", "\\_")


def pct(x, d=1):
    return f"{100 * x:.{d}f}\\%"


def macro_name(s):
    # LaTeX macro names: letters only
    return re.sub(r"[^A-Za-z]", "", s.title().replace("_", ""))


macros = {}
env = R["environment"]
se = R["scenario_eval"]
macros.update({
    "NSeeds": len(se["seeds"]), "NPerSeed": se["n_per_seed"], "NPerScenario": se["n_per_seed"] * len(se["seeds"]),
    "NCalib": se["n_calib"], "ActDim": se["activation_dim"], "TinyLayers": se["n_layers"],
    "TinyParams": f"{se['n_params']:,}".replace(",", "{,}"),
    "MChannels": f"{A['m_channels']:,}".replace(",", "{,}"),
    "PSingleZFour": f"{A['p_single_z4']:.2e}".replace("e-0", "\\times 10^{-") + "}",
    "PredFPRZFour": pct(A["predicted_fpr_z4"]), "EmpFPRZFour": pct(A["empirical_fpr_z4"]),
    "ZBonf": f"{A['z_bonferroni']:.2f}", "EmpFPRBonf": pct(A["empirical_fpr_bonf"]),
    "ExpMaxGauss": f"{A['expected_max_gaussian']:.2f}", "CleanMaxZMean": f"{A['clean_max_z_mean']:.2f}",
    "CleanMaxZPNinetyNine": f"{A['clean_max_z_p99']:.2f}",
    "SynergyTPRBonf": pct(A["tpr_at_bonf"]["SYNERGY"]),
    "PyVer": env["python"], "NpVer": env["numpy"], "CPUCount": env["cpu_count"],
    "WallTime": f"{R['wall_time_s']:.0f}",
    "AUCSynergy": f"{R['roc']['SYNERGY']['auc']:.2f}",
})
for k, v in SC.items():
    n = macro_name(k)
    macros[f"Flag{n}"] = pct(v["flag_rate_mean"])
    macros[f"Type{n}"] = pct(v["type_accuracy_mean"])
    macros[f"Mon{n}"] = pct(v["monitor_only_flag_rate"])
    macros[f"Lat{n}"] = f"{v['latency_ms_mean']:.2f}"
    macros[f"LatP{n}"] = f"{v['latency_ms_p99']:.2f}"
    macros[f"Att{n}"] = f"{v['attest_ms_mean']:.2f}"
    macros[f"MonMs{n}"] = f"{v['monitor_ms_mean']:.2f}"
lat_all = [v["latency_ms_mean"] for v in SC.values()]
macros["LatMin"] = f"{min(lat_all):.2f}"
macros["LatMax"] = f"{max(lat_all):.2f}"
macros["LatPMax"] = f"{max(v['latency_ms_p99'] for v in SC.values()):.1f}"
thr = [r["throughput_mb_s"] for r in R["merkle_scaling"] if r["size_mb"] > 100]
macros["MerkThrMin"] = f"{min(thr):.0f}"
macros["MerkThrMax"] = f"{max(thr):.0f}"
macros["SafetyAdvFrac"] = pct(SC["ADV_SAFETY_BYPASS"]["confusion"]["ADVERSARIAL_INPUT"] / 1000)
macros["SafetyTFFrac"] = pct(SC["ADV_SAFETY_BYPASS"]["confusion"]["TRANSIENT_FAULT"] / 1000)
macros["CleanAdvFrac"] = pct(SC["CLEAN"]["confusion"].get("ADVERSARIAL_INPUT", 0) / 1000)
macros["CleanTFFrac"] = pct(SC["CLEAN"]["confusion"].get("TRANSIENT_FAULT", 0) / 1000)
for row in R["merkle_scaling"]:
    n = macro_name(row["profile"].split("-INT8")[0].replace(".", "p").replace("-", " "))
    macros[f"MerkVer{n}"] = f"{row['verify_s_mean'] * 1e3:.1f}"
    macros[f"MerkSize{n}"] = f"{row['size_mb']:.1f}"
    macros[f"MerkThr{n}"] = f"{row['throughput_mb_s']:.0f}"
for k, v in R["extraction_fidelity"].items():
    macros[f"Fid{macro_name(k)}"] = f"{v['mean_fidelity']:.5f}"

with open(OUT / "numbers.tex", "w") as f:
    f.write("% AUTO-GENERATED by experiments/make_tables.py -- do not edit\n")
    for k, v in macros.items():
        f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

# --- main results table -----------------------------------------------------
with open(OUT / "tab_scenarios.tex", "w") as f:
    f.write("% AUTO-GENERATED\n\\begin{tabular}{lrrrrr}\n\\toprule\n")
    f.write("\\textbf{Scenario} & \\textbf{Monitor only} & \\textbf{Flagged} & \\textbf{Correct label} "
            "& \\textbf{Mean (ms)} & \\textbf{p99 (ms)} \\\\\n\\midrule\n")
    for k, v in SC.items():
        f.write(f"{LABEL[k]} & {pct(v['monitor_only_flag_rate'])} & "
                f"{pct(v['flag_rate_mean'])} $\\pm$ {100 * v['flag_rate_std']:.1f} & "
                f"{pct(v['type_accuracy_mean'])} $\\pm$ {100 * v['type_accuracy_std']:.1f} & "
                f"{v['latency_ms_mean']:.2f} & {v['latency_ms_p99']:.2f} \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")

# --- per-seed table (appendix) ---------------------------------------------
with open(OUT / "tab_per_seed.tex", "w") as f:
    seeds = se["seeds"]
    f.write("% AUTO-GENERATED\n\\begin{tabular}{l" + "rr" * len(seeds) + "}\n\\toprule\n")
    f.write("& " + " & ".join(f"\\multicolumn{{2}}{{c}}{{Seed {s}}}" for s in seeds) + " \\\\\n")
    f.write("\\textbf{Scenario} & " + " & ".join(["Flag", "Label"] * len(seeds)) + " \\\\\n\\midrule\n")
    # per-seed numbers were not stored per scenario in summary; recompute from results.json raw
    for k in SC:
        raw = R["scenario_eval"]["scenarios"][k]
        f.write(LABEL[k].replace("Training-data exfil.\\ probe", "Exfil.\\ probe"))
        for s in raw.get("per_seed", []):
            f.write(f" & {100 * s['flag_rate']:.1f} & {100 * s['type_accuracy']:.1f}")
        f.write(" \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")

# --- raw confusion counts (appendix) ---------------------------------------
cols = ["CLEAN", "WEIGHT_TAMPER", "SUPPLY_CHAIN_BACKDOOR", "ADVERSARIAL_INPUT", "TRANSIENT_FAULT",
        "TRAINING_DATA_EXFILTRATION", "JAILBREAK", "PROMPT_INJECTION"]
short = ["Clean", "W.T.", "S.C.", "Adv.", "T.F.", "Exf.", "Jb.", "P.I."]
with open(OUT / "tab_confusion_counts.tex", "w") as f:
    f.write("% AUTO-GENERATED\n\\begin{tabular}{l" + "r" * len(cols) + "}\n\\toprule\n")
    f.write("\\textbf{Scenario} & " + " & ".join(f"\\textbf{{{s}}}" for s in short) + " \\\\\n\\midrule\n")
    for k, v in SC.items():
        f.write(LABEL[k] + " & " + " & ".join(str(v["confusion"].get(c, 0)) for c in cols) + " \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")

# --- Merkle scaling ---------------------------------------------------------
with open(OUT / "tab_merkle.tex", "w") as f:
    f.write("% AUTO-GENERATED\n\\begin{tabular}{lrrrrrc}\n\\toprule\n")
    f.write("\\textbf{Stub profile} & \\textbf{Tensors} & \\textbf{Params} & \\textbf{MiB} & "
            "\\textbf{Build (ms)} & \\textbf{Verify (ms)} & \\textbf{1-bit tamper localised} \\\\\n\\midrule\n")
    for r in R["merkle_scaling"]:
        f.write(f"{r['profile']} & {r['n_tensors']} & {r['n_params']:,} & {r['size_mb']:.1f} & "
                f"{r['build_s'] * 1e3:.1f} & {r['verify_s_mean'] * 1e3:.1f} & "
                f"{'yes' if r['tamper_detected'] else 'no'} \\\\\n".replace(",", "{,}"))
    f.write("\\bottomrule\n\\end{tabular}\n")

# --- stub profiles ----------------------------------------------------------
with open(OUT / "tab_profiles.tex", "w") as f:
    f.write("% AUTO-GENERATED\n\\begin{tabular}{lrrrrrr}\n\\toprule\n")
    f.write("\\textbf{Profile key} & \\textbf{Blocks} & \\textbf{Hidden} & \\textbf{FFN} & "
            "\\textbf{Vocab} & \\textbf{Tensors} & \\textbf{Stub params} \\\\\n\\midrule\n")
    for k, p in R["stub_profiles"].items():
        f.write(f"\\texttt{{{k}}} & {p['n_layers']} & {p['hidden']:,} & {p['ffn']:,} & {p['vocab']:,} & "
                f"{p['n_tensors']} & {p['n_params']:,} \\\\\n".replace(",", "{,}").replace("\\texttt{{,}}", ","))
    f.write("\\bottomrule\n\\end{tabular}\n")

# --- extraction fidelity -----------------------------------------------------
with open(OUT / "tab_extraction.tex", "w") as f:
    f.write("% AUTO-GENERATED\n\\begin{tabular}{lrr}\n\\toprule\n")
    f.write("\\textbf{Channel model} & \\textbf{Mean cosine fidelity} & \\textbf{Std.\\ over seeds} \\\\\n\\midrule\n")
    nice = {"memory_dump": "Memory dump (no noise)", "cold_boot": "Cold boot (0.2\\% single-bit decay)",
            "em_side_channel": "EM side channel (2.5\\% $\\pm 1$ LSB)"}
    for k, v in R["extraction_fidelity"].items():
        f.write(f"{nice[k]} & {v['mean_fidelity']:.5f} & {v['std']:.1e} \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")

# --- test inventory (appendix) from pytest collection ----------------------
proc = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-o", "addopts=", "tests"],
                      cwd=ROOT.parent, capture_output=True, text=True,
                      env={**__import__("os").environ, "PYTHONPATH": str(ROOT.parent / "src")})
ids, mod, cls = [], None, None
for line in proc.stdout.splitlines():
    m = re.match(r"\s*<(Module|Class|Function) (\S+)>", line)
    if not m:
        continue
    kind, name = m.groups()
    if kind == "Module":
        mod, cls = name, None
    elif kind == "Class":
        cls = name
    else:
        ids.append("::".join(x for x in ("tests/" + mod, cls, name) if x))
with open(OUT / "tab_tests.tex", "w") as f:
    f.write("% AUTO-GENERATED from pytest --collect-only\n")
    f.write("\\begin{longtable}{p{0.33\\textwidth}p{0.6\\textwidth}}\n\\toprule\n"
            "\\textbf{File / class} & \\textbf{Test} \\\\\n\\midrule\n\\endhead\n")
    for i in ids:
        parts = i.split("::")
        where = parts[0].replace("tests/", "") + ("::" + parts[1] if len(parts) > 2 else "")
        name = parts[-1]
        brk = lambda t: t.replace("_", "\\_\\allowbreak{}").replace("::", "::\\allowbreak{}")
        f.write(f"\\texttt{{\\footnotesize {brk(where)}}} & "
                f"\\texttt{{\\footnotesize {brk(name)}}} \\\\\n")
    f.write("\\bottomrule\n\\end{longtable}\n")
with open(OUT / "numbers.tex", "a") as f:
    f.write(f"\\newcommand{{\\NTests}}{{{len(ids)}}}\n")

print(f"wrote {len(macros) + 1} macros, {len(ids)} tests ->", OUT)
