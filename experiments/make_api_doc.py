#!/usr/bin/env python3
"""Generate report/generated/api.tex: public classes/functions with signatures
and the first line of each docstring, by introspection of the installed source."""
import importlib, inspect, re
from pathlib import Path

MODS = ["edgeguard.attestation.merkle", "edgeguard.attestation.manager",
        "edgeguard.detection.statistics", "edgeguard.detection.calibration",
        "edgeguard.detection.monitor", "edgeguard.classifier.classifier",
        "edgeguard.classifier.rules", "edgeguard.llm.model", "edgeguard.llm.detector",
        "edgeguard.attacks.bitflip", "edgeguard.attacks.weight_extraction",
        "edgeguard.attacks.training_data_recovery", "edgeguard.attacks.supply_chain",
        "edgeguard.attacks.adversarial", "edgeguard.attacks.synergy",
        "edgeguard.instrumentation.hooks", "edgeguard.instrumentation.qnn_adapter",
        "edgeguard.utils.crypto", "edgeguard.utils.quantization"]

def tex(s):
    s = s.replace("\\", "\\textbackslash{}")
    for a, b in (("_", "\\_"), ("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("{", "\\{"), ("}", "\\}"),
                 ("$", "\\$"), ("~", "\\textasciitilde{}"), ("^", "\\textasciicircum{}")):
        s = s.replace(a, b)
    s = s.replace("\\textbackslash\\{\\}", "\\textbackslash{}")
    for a, b in (("≈", "$\\approx$"), ("→", "$\\to$"), ("—", "---"), ("–", "--"), ("≥", "$\\ge$"),
                 ("≤", "$\\le$"), ("×", "$\\times$"), ("•", "-"), ("✓", "ok"), ("✗", "x")):
        s = s.replace(a, b)
    return "".join(ch if ord(ch) < 128 else "?" for ch in s)

def brk(s):
    return s.replace("\\_", "\\_\\allowbreak{}").replace(", ", ",\\allowbreak{} ").replace("(", "(\\allowbreak{}")

def first_line(obj):
    d = inspect.getdoc(obj) or ""
    return d.strip().split("\n")[0] if d else ""

def sig(f):
    try:
        s = str(inspect.signature(f))
    except (TypeError, ValueError):
        return "(...)"
    s = re.sub(r"<[^>]+>", "...", s)
    return s if len(s) < 110 else s[:107] + "...)"

out = ["% AUTO-GENERATED by experiments/make_api_doc.py"]
for mname in MODS:
    m = importlib.import_module(mname)
    out.append(f"\\subsection*{{\\texttt{{{tex(mname)}}}}}")
    out.append("\\begin{itemize}[leftmargin=*,itemsep=1pt]")
    for name, obj in inspect.getmembers(m):
        if name.startswith("_") or getattr(obj, "__module__", None) != mname:
            continue
        if inspect.isclass(obj):
            out.append(f"\\item \\textbf{{class \\texttt{{{tex(name)}}}}} --- {tex(first_line(obj))}")
            meths = [(n, f) for n, f in inspect.getmembers(obj)
                     if not n.startswith("_") and (inspect.isfunction(f) or inspect.ismethod(f))
                     and f.__qualname__.split(".")[0] == name]
            if meths:
                out.append("\\begin{itemize}[leftmargin=1.2em,itemsep=0pt]")
                for n, f in meths:
                    out.append(f"\\item \\texttt{{\\small {brk(tex(n + sig(f)))}}}"
                               + (f" --- {tex(first_line(f))}" if first_line(f) else ""))
                out.append("\\end{itemize}")
        elif inspect.isfunction(obj):
            out.append(f"\\item \\texttt{{\\small {brk(tex(name + sig(obj)))}}} --- {tex(first_line(obj))}")
    out.append("\\end{itemize}")
Path("report/generated/api.tex").write_text("\n".join(out) + "\n")
print("api.tex lines:", len(out))
